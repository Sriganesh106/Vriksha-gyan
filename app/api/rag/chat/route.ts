import { NextRequest, NextResponse } from 'next/server';
import { queryAyurvedaKnowledge } from '@/app/lib/ragChroma';

const GEMINI_API_KEY = process.env.GEMINI_API_KEY || '';
const GEMINI_URL = `https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash-lite:generateContent?key=${GEMINI_API_KEY}`;

export async function POST(req: NextRequest) {
  try {
    const { message } = await req.json();

    if (!message || typeof message !== 'string') {
      return NextResponse.json({ error: 'Message is required' }, { status: 400 });
    }

    console.log('\n=================== 🌿 RAG CHAT QUERY ===================');
    console.log(`📩 User Query: "${message}"`);

    const retrievedDocs = await queryAyurvedaKnowledge(message, 4);

    let contextSection = '';
    let sourcesList: Array<{ source: string; page?: number }> = [];

    if (retrievedDocs && retrievedDocs.length > 0) {
      console.log(`🔍 Retrieved ${retrievedDocs.length} chunks from ChromaDB:`);
      retrievedDocs.forEach((doc, idx) => {
        console.log(`   [${idx + 1}] ${doc.source}${doc.page ? ` (p. ${doc.page})` : ''} - distance: ${doc.distance !== undefined ? doc.distance.toFixed(4) : 'N/A'}`);
      });

      contextSection = retrievedDocs
        .map((doc, idx) => `[Source ${idx + 1}: ${doc.source}${doc.page ? ` (Page ${doc.page})` : ''}]\n${doc.text}`)
        .join('\n\n---\n\n');

      sourcesList = retrievedDocs.map((doc) => ({
        source: doc.source,
        page: doc.page,
      }));
    } else {
      console.log('⚠️ No matching chunks found in ChromaDB for this query.');
    }

    const augmentedPrompt = `You are Dr. Vaidya, a master Ayurvedic physician and scholar with 30+ years of classical and evidence-based clinical experience.

You have access to verified excerpts from traditional and evidence-based Ayurvedic texts:
---------------------
VERIFIED AYURVEDIC KNOWLEDGE:
${contextSection || 'No specific document excerpts found. Rely on classical Ayurvedic principles with standard precautions.'}
---------------------

USER QUESTION: "${message}"

INSTRUCTIONS:
1. Ground your answer in classical and evidence-based Ayurvedic medicine, integrating the verified knowledge provided above.
2. Speak naturally and authoritatively as Dr. Vaidya. DO NOT say meta-references like "(Source 1)", "(Page 12)", "in the provided excerpts", "unprovided pages", "loaded into our system", or "in our repository". Speak seamlessly as a knowledgeable physician.
3. If specific details for a condition are not in the classical guidelines provided, still provide authentic Ayurvedic dietary and lifestyle recommendations (Ahara & Vihara) with standard professional clinical precautions.
4. Structure your answer cleanly:
   - 🙏 Namaste greeting
   - Botanical & Sanskrit name (if querying a plant/herb) or Ayurvedic understanding of the condition (e.g. Dosha imbalance)
   - Classical formulations, preparations, or remedies
   - Recommended dosage, vehicle (Anupana), and timing
   - Safety, precautions & contraindications
5. Tone: Warm, respectful, authentic, and clinically responsible.
6. Clearly advise consulting a certified Ayurvedic doctor or emergency facility for severe or persistent conditions.`;

    const geminiRes = await fetch(GEMINI_URL, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [
          {
            role: 'user',
            parts: [{ text: augmentedPrompt }],
          },
        ],
        generationConfig: {
          temperature: 0.6,
          topK: 40,
          topP: 0.9,
          maxOutputTokens: 2048,
        },
      }),
    });

    if (!geminiRes.ok) {
      const errorText = await geminiRes.text();
      throw new Error(`Gemini API failed (${geminiRes.status}): ${errorText}`);
    }

    const data = await geminiRes.json();
    const candidate = data.candidates?.[0]?.content?.parts?.[0]?.text;

    if (!candidate) {
      throw new Error('No answer generated by Gemini');
    }

    console.log(`🤖 Dr. Vaidya Response (${candidate.length} chars):\n${candidate.substring(0, 300)}...`);
    console.log('==========================================================\n');

    return NextResponse.json({
      answer: candidate,
      sources: sourcesList,
      ragUsed: retrievedDocs.length > 0,
    });
  } catch (error: any) {
    console.error('RAG Chatbot Error:', error);
    return NextResponse.json(
      { error: error.message || 'Internal Server Error' },
      { status: 500 }
    );
  }
}
